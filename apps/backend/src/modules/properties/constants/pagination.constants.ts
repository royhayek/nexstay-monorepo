/**
 * Helper function to validate and normalize pagination parameters
 */
export function validatePagination(
  page?: number,
  limit?: number,
  maxLimit: number = PAGINATION_CONSTANTS.MAX_LIMIT,
) {
  return {
    page: Math.max(PAGINATION_CONSTANTS.DEFAULT_PAGE, page || PAGINATION_CONSTANTS.DEFAULT_PAGE),
    limit: Math.min(
      Math.max(PAGINATION_CONSTANTS.MIN_LIMIT, limit || PAGINATION_CONSTANTS.DEFAULT_LIMIT),
      maxLimit,
    ),
  };
}
